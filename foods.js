// สร้างรายการฐานข้อมูล
function makeFood(row, index, type) {
  const [
    name, category, calories, protein, carbs, fat,
    fiber, sugar, sodium, saturatedFat
  ] = row;

  const estimated = type === "menu";

  return {
    id: `${type}-${index + 1}`,
    name,
    category,
    unit: "g",
    calories,
    protein,
    carbs,
    fat,
    fiber,
    sugar,
    sodium,
    saturatedFat,
    source: estimated
      ? "ค่าประมาณเพื่อการติดตามอาหาร"
      : "ค่าทั่วไปจากฐานข้อมูลองค์ประกอบอาหาร / ฉลากอาจแตกต่าง",
    note: estimated
      ? "ค่าประมาณต่อ 100 กรัม สูตรและปริมาณจริงแตกต่างกันตามร้าน"
      : "ค่าต่อ 100 กรัม วัตถุดิบดิบหรือสภาพตามชื่อรายการ"
  };
}

